def write_sheet(wb, name, rows):
    ws = wb.create_sheet(name) if name not in wb.sheetnames else wb[name]
    ws.delete_rows(1, ws.max_row)
    ws.append(HEADER)
    for r in rows:
        ws.append([r[h] for h in HEADER])
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions


def load_sheet(name, path=WORKBOOK_PATH):
    wb = openpyxl.load_workbook(path)
    ws = wb[name]
    keys = [c.value for c in ws[1]]
    return [dict(zip(keys, [c.value for c in row])) for row in list(ws.rows)[1:]]


def validate_counts(sheets):
    expected = {"Retrieval": 50, "Response": 50, "Reasoning": 35, "Report": 20}
    for name, want in expected.items():
        got = len(sheets.get(name, []))
        assert got == want, f"{name}: got {got} want {want}"


def validate_distribution(sheets):
    expected = {
        "Retrieval": {"L1": 12, "L2": 16, "L3": 12, "L4": 10},
        "Response": {"L1": 12, "L2": 16, "L3": 12, "L4": 10},
        "Reasoning": {"L1": 8, "L2": 12, "L3": 10, "L4": 5},
        "Report": {"L1": 4, "L2": 6, "L3": 6, "L4": 4},
    }
    for name, want in expected.items():
        counts = Counter(r.get("Complexity") for r in sheets.get(name, []))
        assert dict(counts) == want, f"{name}: got {dict(counts)} want {want}"


def validate_agents(sheets):
    all_7_agents = {
        "Curriculum and Instruction Agent",
        "Research Agent",
        "Extension Agent",
        "Quality Assurance Agent",
        "Faculty Agent",
        "Student Support Agent",
        "Facilities Agent",
    }
    for name, rows in sheets.items():
        agents_in_sheet = set(r.get("ExpectedAgent") for r in rows)
        missing = all_7_agents - agents_in_sheet
        assert not missing, f"{name} is missing agents: {missing}"


def check_workbook(path=WORKBOOK_PATH):
    try:
        sheets = {name: load_sheet(name, path) for name in SHEET_NAMES}
    except Exception as exc:
        return [f"workbook unreadable: {exc}"]
    try:
        validate_counts(sheets)
        validate_distribution(sheets)
        validate_agents(sheets)
    except AssertionError as exc:
        return [f"FAIL {exc}"]
    return []


def build_workbook(path=WORKBOOK_PATH):
    wb = openpyxl.Workbook()
    wb.remove(wb.active)  # remove default Sheet
    for name in SHEET_NAMES:
        write_sheet(wb, name, ROWS_BY_SHEET[name])
    wb.save(path)


def main(argv):
    if "--check" in argv:
        pos = [a for a in argv if not a.startswith("-")]
        path = pos[0] if pos else WORKBOOK_PATH
        sheets = {name: load_sheet(name, path) for name in SHEET_NAMES}
        for name in SHEET_NAMES:
            c = Counter(r.get("Complexity") for r in sheets.get(name, []))
            print(f"{name}: {len(sheets[name])} (L1={c['L1']} L2={c['L2']} L3={c['L3']} L4={c['L4']})")
        errors = check_workbook(path)
        if errors:
            for e in errors:
                print(e)
            return 1
        print("PASS: all 155 queries, distributions, and 7-agent coverage valid!")
        return 0

    build_workbook()
    errors = check_workbook()
    if errors:
        for e in errors:
            print(e)
        return 1
    print(f"PASS: workbook successfully built at {WORKBOOK_PATH} with 155 queries!")
    return 0


