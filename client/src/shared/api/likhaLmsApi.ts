import { getToken } from './client';

export const LIKHA_URL =
  (typeof import.meta !== 'undefined' && import.meta.env?.VITE_LIKHA_URL) ||
  'https://gabay.zyberlab.com';

export interface LikhaUploadedFile {
  id: string;
  filename_download: string;
  url: string;
}

function getAuthHeaders(): Record<string, string> {
  const headers: Record<string, string> = {
    'Content-Type': 'application/json',
  };
  const token = getToken();
  if (token) {
    headers.Authorization = `Bearer ${token}`;
  }
  return headers;
}

export const likhaLmsApi = {
  /**
   * Fetches courses with deep nested relations (activities, modules, module items, files).
   */
  async getCoursesWithRelations(): Promise<any[]> {
    const fields = 'fields=*,activities.*,modules.*,modules.items.*,course_files.*';
    const res = await fetch(`${LIKHA_URL}/items/courses?${fields}`, {
      headers: getAuthHeaders(),
    });
    if (!res.ok) {
      throw new Error(`Failed to fetch courses from Likha: ${res.status}`);
    }
    const json = await res.json();
    return json.data || [];
  },

  /**
   * Fetches activities for a specific course with nested questions and rubrics.
   */
  async getActivitiesWithRelations(courseId: string): Promise<any[]> {
    const query = `filter[course_id][_eq]=${encodeURIComponent(courseId)}&fields=*,questions.*,rubrics.*`;
    const res = await fetch(`${LIKHA_URL}/items/activities?${query}`, {
      headers: getAuthHeaders(),
    });
    if (!res.ok) {
      throw new Error(`Failed to fetch activities: ${res.status}`);
    }
    const json = await res.json();
    return json.data || [];
  },

  /**
   * Directly uploads a file or image to Likha ERP /files and returns its asset URL.
   */
  async uploadFile(file: File): Promise<LikhaUploadedFile> {
    const formData = new FormData();
    formData.append('file', file);

    const token = getToken();
    const headers: Record<string, string> = {};
    if (token) {
      headers.Authorization = `Bearer ${token}`;
    }

    const res = await fetch(`${LIKHA_URL}/files`, {
      method: 'POST',
      headers,
      body: formData,
    });

    if (!res.ok) {
      throw new Error(`File upload to Likha failed: ${res.status}`);
    }

    const json = await res.json();
    const fileData = json.data;
    return {
      id: fileData.id,
      filename_download: fileData.filename_download || file.name,
      url: `${LIKHA_URL}/assets/${fileData.id}`,
    };
  },

  /**
   * Authenticates directly against Likha ERP.
   */
  async loginLikhaUser(email: string, password: string): Promise<{ token: string; user: any }> {
    const res = await fetch(`${LIKHA_URL}/auth/login`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email, password }),
    });

    if (!res.ok) {
      throw new Error(`Likha authentication failed: ${res.status}`);
    }

    const json = await res.json();
    const token = json.data?.access_token;

    // Fetch user details
    const meRes = await fetch(`${LIKHA_URL}/users/me?fields=*,role.*`, {
      headers: { Authorization: `Bearer ${token}` },
    });
    const meJson = await meRes.json();

    return {
      token,
      user: meJson.data,
    };
  },

  /**
   * Fetches user in-app notifications generated by Likha Flows.
   */
  async getNotifications(userId: string): Promise<any[]> {
    const res = await fetch(
      `${LIKHA_URL}/items/notifications?filter[user_id][_eq]=${encodeURIComponent(userId)}&sort=-created_at&limit=50`,
      { headers: getAuthHeaders() }
    );
    if (!res.ok) return [];
    const json = await res.json();
    return json.data || [];
  },

  /**
   * Saves or updates an activity directly on Likha ERP with relational child items.
   */
  async saveActivity(activity: any): Promise<any> {
    const { questions, rubric, ...rootPayload } = activity;
    const isUpdate = Boolean(rootPayload.id);
    const url = isUpdate
      ? `${LIKHA_URL}/items/activities/${encodeURIComponent(rootPayload.id)}`
      : `${LIKHA_URL}/items/activities`;
    const res = await fetch(url, {
      method: isUpdate ? 'PATCH' : 'POST',
      headers: getAuthHeaders(),
      body: JSON.stringify(rootPayload),
    });
    if (!res.ok) {
      throw new Error(`Failed to save activity: ${res.status}`);
    }
    const json = await res.json();
    const saved = json.data || rootPayload;
    const actId = saved.id || rootPayload.id;

    // Relational child items to assessment_questions
    if (Array.isArray(questions) && questions.length > 0) {
      for (let i = 0; i < questions.length; i++) {
        const q = questions[i];
        await fetch(`${LIKHA_URL}/items/assessment_questions`, {
          method: 'POST',
          headers: getAuthHeaders(),
          body: JSON.stringify({
            id: q.id || `q-${actId}-${i}`,
            activity_id: actId,
            question_text: q.question_text || q.text || q.prompt || '',
            question_type: q.question_type || q.type || 'essay',
            points: Number(q.points) || 10,
            correct_answer: q.correct_answer || q.correctAnswer || null,
            options_json: typeof q.options === 'string' ? q.options : JSON.stringify(q.options || []),
            order: i + 1,
          }),
        }).catch(() => {});
      }
    }

    // Relational child items to rubric_criteria
    if (Array.isArray(rubric) && rubric.length > 0) {
      for (let i = 0; i < rubric.length; i++) {
        const r = rubric[i];
        await fetch(`${LIKHA_URL}/items/rubric_criteria`, {
          method: 'POST',
          headers: getAuthHeaders(),
          body: JSON.stringify({
            id: r.id || `rub-${actId}-${i}`,
            activity_id: actId,
            title: r.title || r.criterion || '',
            description: r.description || '',
            max_points: Number(r.max_points ?? r.points) || 10,
            order: i + 1,
          }),
        }).catch(() => {});
      }
    }

    return { ...saved, questions: questions || [], rubric: rubric || [] };
  },

  /**
   * Submits an activity response directly to Likha ERP with relational answers.
   */
  async submitActivity(submission: any): Promise<any> {
    const { answers, ...rootPayload } = submission;
    const subId = rootPayload.id || `sub-${Date.now().toString(36)}`;
    const res = await fetch(`${LIKHA_URL}/items/submissions`, {
      method: 'POST',
      headers: getAuthHeaders(),
      body: JSON.stringify({ id: subId, ...rootPayload }),
    });
    if (!res.ok) {
      throw new Error(`Failed to submit activity: ${res.status}`);
    }

    // Relational child items to submission_answers
    const answersList = Array.isArray(answers)
      ? answers
      : typeof answers === 'object' && answers !== null
        ? Object.entries(answers).map(([qid, val]) => ({ questionId: qid, answer: String(val) }))
        : [];

    for (let i = 0; i < answersList.length; i++) {
      const a = answersList[i];
      await fetch(`${LIKHA_URL}/items/submission_answers`, {
        method: 'POST',
        headers: getAuthHeaders(),
        body: JSON.stringify({
          id: `sa-${subId}-${i}`,
          submission_id: subId,
          question_id: a.questionId || a.question_id || `q-${i}`,
          student_answer: a.answer || a.studentAnswer || String(a),
          awarded_points: a.points ?? null,
          feedback: a.feedback || null,
        }),
      }).catch(() => {});
    }

    const json = await res.json();
    return { ...json.data, answers: answersList };
  },

  /**
   * Grades a student submission directly on Likha ERP (triggers Flow 2).
   */
  async gradeSubmission(submissionId: string, score: number, feedback?: string): Promise<any> {
    const res = await fetch(`${LIKHA_URL}/items/submissions/${encodeURIComponent(submissionId)}`, {
      method: 'PATCH',
      headers: getAuthHeaders(),
      body: JSON.stringify({
        score,
        feedback,
        status: 'graded',
        graded_at: new Date().toISOString(),
      }),
    });
    if (!res.ok) {
      throw new Error(`Failed to grade submission: ${res.status}`);
    }
    const json = await res.json();
    return json.data;
  },

  /**
   * Fetches course grades with nested SPR cells.
   */
  async getCourseGrades(courseId: string): Promise<any[]> {
    const res = await fetch(
      `${LIKHA_URL}/items/course_grades?filter[course_id][_eq]=${encodeURIComponent(courseId)}&fields=*,spr_cells.*`,
      { headers: getAuthHeaders() }
    );
    if (!res.ok) return [];
    const json = await res.json();
    return json.data || [];
  },
};
